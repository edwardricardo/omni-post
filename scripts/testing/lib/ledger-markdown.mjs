// @ts-check
/**
 * @file ledger-markdown.mjs
 * @description Renders the test ledger as `LEDGER.md`, the page a reviewer reads beside the
 *   overlay: the summary, one section per demolition slice with its expected drop, then the rows
 *   no slice holds. Each row shows its verdict and, in the status column, `machine` or the
 *   confirmation over the machine's verdict, so the two stay visible side by side. The tables are
 *   the legal and support pages' (`renderTable`), formatted by Prettier under this repository's
 *   configuration for the page, so `pnpm format:check` passes over the committed copy. No clock, no
 *   commit and no absolute path: equal ledgers render equal bytes.
 * @layer infrastructure
 */
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import { renderTable } from "../../legal/lib/inventory.mjs";
import { OVERLAY_DIR, dropWords } from "./ledger-overlay.mjs";

/** Where the page is committed: beside the overlay it renders, under `docs/`. */
export const MARKDOWN_FILE = `${OVERLAY_DIR}/LEDGER.md`;
const MARKDOWN_PATH = fileURLToPath(new URL(`../../../${MARKDOWN_FILE}`, import.meta.url));
const COLUMNS = ["Path", "Shape", "Blocks", "Decorative", "Verdict", "Status", "Basis"];
const UNMEASURED = "unmeasured";

/**
 * @typedef {import("./ledger-core.mjs").FileRow} FileRow
 * @typedef {import("./ledger-core.mjs").Ledger} Ledger
 * @typedef {ReadonlyMap<string, FileRow["verdict"]>} MachineVerdicts Each row's machine verdict,
 *   before the overlay.
 */

/**
 * @description Renders one row's cells.
 * @param {FileRow} row
 * @param {MachineVerdicts} machine
 * @returns {string[]}
 */
function cells(row, machine) {
  const decorative = row.blocks.filter((block) => block.criteria.length > 0).length;
  const status =
    row.status === "confirmed"
      ? `confirmed (machine: ${machine.get(row.path) ?? UNMEASURED})`
      : "machine";
  return [
    `\`${row.path}\``,
    row.shape ?? "none",
    `${row.blockCount}`,
    `${decorative}`,
    row.verdict ?? UNMEASURED,
    status,
    row.basis,
  ];
}

/**
 * @description Renders the ledger as the Markdown page that is committed.
 * @param {Ledger} ledger
 * @param {MachineVerdicts} machine Each row's verdict before the overlay confirmed it.
 * @returns {Promise<string>} The page, ending in a newline.
 */
export async function renderMarkdown(ledger, machine) {
  const { files, rows, blocks } = ledger.summary;
  /** @type {(selected: readonly FileRow[]) => string} */
  const table = (selected) =>
    renderTable(
      COLUMNS,
      selected.map((row) => cells(row, machine))
    );
  const measures = [
    ["Files", files.total],
    ...Object.entries(files.byVerdict),
    ["Machine rows", rows.machine],
    ["Confirmed rows", rows.confirmed],
    ["Blocks", blocks.total],
    ["Blocks with a criterion", blocks.decorative],
  ].map(([measure, count]) => [`${measure}`, `${count}`]);
  const slices = Object.entries(ledger.slices).flatMap(([id, slice]) => [
    `## Slice ${id}`,
    `Expected drop: ${dropWords(slice.expectedDrop)}.`,
    table(ledger.files.filter((row) => row.sliceId === id)),
  ]);
  const markdown = [
    "# Test ledger",
    "> Generated by `scripts/testing/ledger.mjs` from the tracked tree and the `adjudications.json` " +
      "and `slices.json` beside this page; never edit it by hand. `pnpm ledger` regenerates it and " +
      "`pnpm check:ledger` fails when it is stale.",
    "## Summary",
    renderTable(["Measure", "Count"], measures),
    ...slices,
    "## Rows without a slice",
    table(ledger.files.filter((row) => row.sliceId === null)),
  ].join("\n\n");
  const config = await prettier.resolveConfig(MARKDOWN_PATH, { editorconfig: true });
  return prettier.format(markdown, { ...config, parser: "markdown" });
}
